/** Committed install icon dimensions and the generator's maskable safe-zone scale. */
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import {
  APP_ICON_VARIANTS, ICON_OUTPUT_DIRECTORY, MASKABLE_ARTWORK_SCALE, TILE_SOURCE,
  maskableDocument, renderAppIcons, tileDocument,
} from '../scripts/render-app-icons.ts'
import { pngSize } from './png-size.ts'

describe('web install icons', () => {
  it('ships the generated bytes for every declared variant at its declared edge', async () => {
    const generated = await renderAppIcons(await readFile(TILE_SOURCE, 'utf8'))
    for (const { variant, png } of generated) {
      const committed = await readFile(join(ICON_OUTPUT_DIRECTORY, variant.file))
      expect(committed).toEqual(png)
      expect(pngSize(committed))
        .toEqual([variant.size, variant.size])
    }
    expect(generated.map(icon => icon.variant)).toEqual(APP_ICON_VARIANTS)
  })

  it('keeps the favicon tile and scales only the maskable artwork', async () => {
    const source = await readFile(TILE_SOURCE, 'utf8')
    const tile = tileDocument(source)
    const maskable = maskableDocument(source)
    expect(tile).toContain('viewBox="0 0 100 100"')
    expect(tile).toContain('<rect width="100" height="100" fill="#FFFFFF"/>')
    expect(tile).not.toContain(`scale(${MASKABLE_ARTWORK_SCALE})`)
    expect(tile).toContain('<g id="qingclaw-app-artwork">')
    expect(maskable).toContain(`transform="translate(50 50) scale(${MASKABLE_ARTWORK_SCALE}) translate(-50 -50)"`)
    expect(maskable.indexOf('<rect width="100" height="100" fill="#FFFFFF"/>'))
      .toBeLessThan(maskable.indexOf(`scale(${MASKABLE_ARTWORK_SCALE})`))
  })

  it('rejects non-PNG bytes and incomplete image headers', () => {
    expect(() => pngSize(Buffer.from('<svg/>'))).toThrow(/PNG IHDR/)
    expect(() => pngSize(Buffer.alloc(33))).toThrow(/PNG IHDR/)
  })

  it('fails loudly on a source without the tile it transforms', () => {
    expect(() => tileDocument('')).toThrow(/no root element/)
    expect(() => tileDocument('<svg viewBox="0 0 24 24"></svg>')).toThrow(/100-unit square view box/)
    expect(() => tileDocument('<svg viewBox="0 0 100 100"></svg>')).toThrow(/no opaque background/)
    expect(() => maskableDocument(
      '<svg viewBox="0 0 100 100"><rect width="100" height="100" fill="#FFFFFF"/></svg>',
    ))
      .toThrow(/no artwork group/)
  })
})
